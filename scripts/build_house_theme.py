#!/usr/bin/env python3
"""Build the "House Glass" theme from the installed Frosted Glass Dark Lite.

Frosted Glass is installed by HACS (themes/Frosted Glass/, gitignored), so its
files get replaced on every update. Rather than editing them, this script copies
the Dark Lite theme, adds the house card styles below, and writes
themes/house_glass.yaml (also gitignored, since it is mostly the upstream theme).

Run it again after Frosted Glass updates, then reload themes in HA
(Developer tools > YAML > Themes):

    python3 scripts/build_house_theme.py

Dashboards pick the theme per view (`theme: House Glass`). It is dark only.
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "themes" / "Frosted Glass" / "Frosted Glass Dark Lite.yaml"
SOURCE_NAME = "Frosted Glass Dark Lite"
OUTPUT = ROOT / "themes" / "house_glass.yaml"
NAME = "House Glass"

# Plain theme variables that replace the upstream values.
VARIABLES = {
    # The house cards have always used 20px corners; upstream uses 18px.
    "ha-card-border-radius": "20px",
    # The shared cards in dashboards/components/shared/ are sized for the
    # kitchen tablet. They scale their contents by this, so on House Glass
    # pages (phones, mostly) they come out at three quarters size. Kitchen
    # Dark doesn't set it, so the tablet stays at full size.
    "shared-card-scale": "0.75",
}

# Appended to the upstream card-mod-card CSS. Cards opt in with
# `card_mod: {class: glass-tile}` (plus `tall` or `row` for padding).
CARD_CSS = """
/* ---- House Glass additions (scripts/build_house_theme.py) ---- */

/* Tappable tile: frosted surface, press-down on tap. A card colors itself by
   setting, in its own card_mod style:
     --tile-rgb: the color as "r, g, b" (e.g. 156, 39, 176)
     --tile-on:  0 = plain glass, 1 = full gradient, border and glow;
                 values in between give a softer tint (e.g. 0.3 at rest). */
ha-card.glass-tile {
  --_on: var(--tile-on, 0);
  --_rgb: var(--tile-rgb, 255, 255, 255);
  background:
    linear-gradient(135deg,
      rgba(var(--_rgb), calc(0.30 * var(--_on))),
      rgba(var(--_rgb), calc(0.15 * var(--_on)))),
    rgba(255, 255, 255, calc(0.04 * (1 - var(--_on)))) !important;
  border: 1px solid color-mix(in srgb,
      rgba(var(--_rgb), 0.6) calc(var(--_on) * 100%),
      rgba(255, 255, 255, 0.08)) !important;
  border-radius: 20px !important;
  box-shadow: 0 4px 18px rgba(var(--_rgb), calc(0.3 * var(--_on))) !important;
  transition: all 0.2s cubic-bezier(0.25, 1, 0.5, 1) !important;
}
ha-card.glass-tile:active {
  transform: scale(0.95);
}
/* Icon above the label (layout: vertical). */
ha-card.glass-tile.tall {
  padding: 10px 4px !important;
}
/* Icon beside the label (layout: horizontal). */
ha-card.glass-tile.row {
  padding: 6px 8px !important;
}

/* Navigation chip: tinted in its own color. Set --tile-rgb as above. */
ha-card.glass-chip {
  background: rgba(var(--tile-rgb, 255, 255, 255), 0.12) !important;
  border: 1px solid rgba(var(--tile-rgb, 255, 255, 255), 0.35) !important;
  border-radius: 20px !important;
}
ha-card.glass-chip:active {
  transform: scale(0.95);
}

/* Section headings (heading cards): small, bold, uppercase, the same look
   as the basement's section labels (zone_lighting.yaml, theater_stage.yaml). */
:host(hui-heading-card) .content {
  font-size: 0.78rem;
  font-weight: 700;
  letter-spacing: 1.2px;
  text-transform: uppercase;
  opacity: 0.85;
  --mdc-icon-size: 16px;
}
"""


class _Dumper(yaml.SafeDumper):
    pass


def _str(dumper, value):
    # Keep the CSS blocks readable as YAML block scalars.
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _str)


def main():
    source = yaml.safe_load(SOURCE.read_text())[SOURCE_NAME]
    theme = dict(source)
    # card-mod reads its CSS from the theme this names, so point it at ourselves.
    theme["card-mod-theme"] = NAME
    if "uix-theme" in theme:
        theme["uix-theme"] = NAME
    theme.update(VARIABLES)
    theme["card-mod-card"] = theme.get("card-mod-card", "").rstrip() + "\n" + CARD_CSS

    header = (
        "# GENERATED by scripts/build_house_theme.py from Frosted Glass Dark Lite.\n"
        "# Don't edit by hand: change the script and run it again.\n"
    )
    text = header + yaml.dump({NAME: theme}, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=1000)
    if OUTPUT.exists() and OUTPUT.read_text() == text:
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)}; reload themes in HA to apply")


if __name__ == "__main__":
    main()
